// Writes data/clockwork-commons/coverage-report.json: for every card and Crown Project, where its rules live and which
// named tests mention it. Run with `npm run coverage:clockwork`; CC-COVER-1 checks that it's complete.
import { readFileSync, writeFileSync } from 'node:fs';

const read = (f) => readFileSync(f, 'utf8');
const manifest = JSON.parse(read('data/clockwork-commons/art-manifest.json'));
const spec = JSON.parse(read('data/clockwork-commons/clockwork_commons_original_cardset.json'));
const supplied = new Set([...spec.basic_cards, ...spec.market_cards, ...spec.public_works].map((c) => c.id));

const tests = ['cards', 'rules', 'simulate', 'crown'].flatMap((name) => {
  const file = `tests/clockwork/${name}.test.ts`;
  return read(file)
    .split(/(?=^\s*it(?:\.each\([^\n]*\))?\()/m)
    .slice(1)
    .map((body) => ({ file, ids: body.split('\n')[0].match(/CC-[A-Za-z0-9_-]+/g) ?? [], body }))
    .filter((t) => t.ids.length);
});
// Crown Projects are tested from one table of expected rewards, one named test per row.
const rewards = /const REWARDS[^]*?\n  };/.exec(read('tests/clockwork/rules.test.ts'))[0];
const hasRewardTest = (key) => new RegExp(`^    ${key}: \\{`, 'm').test(rewards);
const rules = ['cards', 'expansions', 'ruleset', 'crown'].map((n) => `src/games/clockwork/rules/${n}.ts`).map((file) => ({ file, text: read(file) }));

const entries = manifest.entries.map(({ key, name }) => {
  const mentioned = tests.filter((t) => t.ids.includes(`CC-CARD-${key}`) || t.body.includes(`'${key}'`));
  const dedicated = mentioned.some((t) => t.ids.includes(`CC-CARD-${key}`)) ? `CC-CARD-${key}` : hasRewardTest(key) ? `CC-PW-${key}` : null;
  return {
    key,
    name,
    source: supplied.has(key) ? 'supplied' : 'added',
    definedIn: rules.find((r) => r.text.includes(`'${key}'`))?.file ?? null,
    dedicatedTest: dedicated,
    alsoIn: [...new Set(mentioned.flatMap((t) => t.ids))].filter((id) => id !== dedicated && id !== 'CC-PW-').sort(),
  };
});

const out = {
  note: 'Generated by scripts/clockwork-coverage.mjs. CC-SIM-ALL also plays every card and claims every Crown Project in full games. Run the named tests with npm test.',
  totals: {
    cards: entries.length,
    supplied: entries.filter((e) => e.source === 'supplied').length,
    added: entries.filter((e) => e.source === 'added').length,
    withDedicatedTest: entries.filter((e) => e.dedicatedTest).length,
  },
  entries,
};
writeFileSync('data/clockwork-commons/coverage-report.json', `${JSON.stringify(out, null, 2)}\n`);
console.log(out.totals, entries.filter((e) => !e.dedicatedTest).map((e) => `${e.key}: ${e.alsoIn.join(',') || 'NONE'}`));
