/**
 * Apex '66 balance and storage report (A8). Plays seeded all-computer races on every circuit and a full room
 * championship, then writes docs/APEX_BALANCE.md. Same seeds, same report. APEX_RACES scales the sample.
 */
import { writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { apex } from '../src/games/apex';
import { aiDraft, aiPlan, aiView } from '../src/games/apex/rules/ai';
import { CIRCUIT_IDS, resolveCircuit } from '../src/games/apex/rules/content/circuits';
import type { AState, AView } from '../src/games/apex/rules/engine';
import { newRace, react, reveal, setPlan, type Level, type Modules, type Race, type Risk } from '../src/games/apex/rules/race';
import { exportReplay } from '../src/games/apex/rules/replay';
import { MemoryStore, RoomCore } from '../src/server/core';

const N = Number(process.env.APEX_RACES ?? 60);
const OFF: Modules = { storm: false, mountains: false, dust: false, rivals: false };
const ON: Modules = { storm: true, mountains: true, dust: true, rivals: true };
const pct = (x: number) => `${Math.round(x * 100)}%`;
const avg = (xs: number[]) => xs.reduce((s, x) => s + x, 0) / Math.max(1, xs.length);
const f1 = (x: number) => x.toFixed(1);

type Spec = { risk: Risk; level: Level };
const RIVALS = ['ortega', 'weiss', 'whitlock', 'arashiro', 'delacroix', 'bellini'];

/** `rivals` rotates the named rivals through the grid slots so an ability, not a slot, is measured. */
function race(circuit: string, modules: Modules, specs: Spec[], seed: string, rivals: number | null = null): Race {
  const r = newRace({
    circuit, laps: resolveCircuit(circuit).laps, seed, modules, event: null,
    cars: specs.map((ai, i) => ({ seat: null, name: `C${i}`, number: i + 1, livery: i, upgrades: [], ai, ...(rivals != null ? { rival: RIVALS[(i + rivals) % RIVALS.length] } : {}) })),
  });
  while (r.phase !== 'over') {
    if (r.round > 300) throw new Error(`${circuit} ${seed}: no finish`);
    for (const c of r.cars) if (!c.done) setPlan(r, c.id, aiPlan(aiView(r, c.id)));
    reveal(r);
    while (r.phase === 'react') react(r, aiDraft(aiView(r, r.pending!.car), r.pending!.hazard));
  }
  return r;
}

const same = (n: number): Spec[] => Array.from({ length: n }, () => ({ risk: 'balanced', level: 'club' }));

it('writes docs/APEX_BALANCE.md', () => {
  const out: string[] = [
    '# Apex ’66 balance and storage',
    '',
    `Generated by \`npm run balance:apex\` (${N} seeded races per row; \`APEX_RACES\` scales it). All cars are computer drivers`,
    'that see only their own view. Identical club/balanced drivers unless a row says otherwise. Same seeds, same report.',
    '',
    '## Circuits (6 identical cars, default laps)',
    '',
    '| Circuit | Corners | Laps | Modules | Rounds (mean, max) | Spins per car | Pole wins | Back-row wins (slots 5–6) | Winning margin (spaces) |',
    '|---|---|---|---|---|---|---|---|---|',
  ];
  const poleShare: number[] = [];
  for (const id of CIRCUIT_IDS) {
    const c = resolveCircuit(id);
    for (const [label, mods] of [['off', OFF], ['on', ON]] as const) {
      const rounds: number[] = [], spins: number[] = [], margins: number[] = [];
      let pole = 0, back = 0;
      for (let s = 0; s < N; s++) {
        const r = race(id, mods, same(6), `bal-${id}-${label}-${s}`);
        rounds.push(r.round);
        spins.push(avg(r.cars.map((x) => x.stats.spins)));
        const win = r.cars[r.finished[0]];
        if (win.stats.grid === 0) pole++;
        if (win.stats.grid >= 4) back++;
        const second = r.cars[r.finished[1]];
        margins.push(second.done!.round > win.done!.round ? win.done!.over + 1 : win.done!.over - second.done!.over);
      }
      poleShare.push(pole / N);
      out.push(`| ${c.name} | ${c.corners.length} | ${c.laps} | ${label} | ${f1(avg(rounds))}, ${Math.max(...rounds)} | ${f1(avg(spins))} | ${pct(pole / N)} | ${pct(back / N)} | ${f1(avg(margins))} |`);
    }
  }
  out.push('', 'An even grid would give each of 6 slots about 17% of wins, so about 33% for the back two. Catch-up helps the last two cars of a 5+ grid, so the back row edges ahead of the front. Margin counts spaces past the line between first and second when they finish in the same round; a full round counts as at least one space more.', '');

  out.push('## Grid sizes (Autodromo Bellavista, modules on)', '', '| Cars | Rounds (mean) | Spins per car | Pole wins | Last-slot wins |', '|---|---|---|---|---|');
  for (const n of [2, 3, 4, 6, 8]) {
    const rounds: number[] = [], spins: number[] = [];
    let pole = 0, last = 0;
    for (let s = 0; s < N; s++) {
      const r = race('bellavista', ON, same(n), `grid-${n}-${s}`);
      rounds.push(r.round);
      spins.push(avg(r.cars.map((x) => x.stats.spins)));
      const g = r.cars[r.finished[0]].stats.grid;
      if (g === 0) pole++;
      if (g === n - 1) last++;
    }
    out.push(`| ${n} | ${f1(avg(rounds))} | ${f1(avg(spins))} | ${pct(pole / N)} | ${pct(last / N)} |`);
  }

  out.push('', '## Driver levels and risk (head to head, 2 cars, alternating pole)', '', '| Pairing | Wins for the first | Spins per race (first, second) |', '|---|---|---|');
  const duel = (a: Spec, b: Spec, circuit: string) => {
    let wins = 0;
    const sa: number[] = [], sb: number[] = [];
    for (let s = 0; s < N; s++) {
      const flip = s % 2 === 1;
      const r = race(circuit, OFF, flip ? [b, a] : [a, b], `duel-${circuit}-${a.level}${a.risk}-${b.level}${b.risk}-${s}`);
      const ia = flip ? 1 : 0;
      if (r.finished[0] === ia) wins++;
      sa.push(r.cars[ia].stats.spins);
      sb.push(r.cars[1 - ia].stats.spins);
    }
    return `${pct(wins / N)} | ${f1(avg(sa))}, ${f1(avg(sb))}`;
  };
  const pairs: [string, Spec, Spec][] = [
    ['works vs novice', { level: 'works', risk: 'balanced' }, { level: 'novice', risk: 'balanced' }],
    ['works vs club', { level: 'works', risk: 'balanced' }, { level: 'club', risk: 'balanced' }],
    ['club vs novice', { level: 'club', risk: 'balanced' }, { level: 'novice', risk: 'balanced' }],
    ['bold vs cautious (club)', { level: 'club', risk: 'bold' }, { level: 'club', risk: 'cautious' }],
    ['balanced vs bold (club)', { level: 'club', risk: 'balanced' }, { level: 'club', risk: 'bold' }],
  ];
  for (const [label, a, b] of pairs) out.push(`| ${label} | ${duel(a, b, 'bellavista')} |`);

  out.push('', '## Racing Rivals (6 named rivals rotated through the grid, modules on, Noordzee Ring)', '', '| Rival | Wins |', '|---|---|');
  const rivalWins = Array(6).fill(0);
  for (let s = 0; s < N; s++) {
    const r = race('noordzee', ON, same(6), `riv-${s}`, s % 6);
    rivalWins[RIVALS.indexOf(r.cars[r.finished[0]].rival!)]++;
  }
  RIVALS.forEach((id, i) => out.push(`| ${id} | ${pct(rivalWins[i] / N)} |`));

  // Storage: one full championship in a real room, measured as the Durable Object would store it.
  const store = new MemoryStore();
  let clock = 1_000_000, ids = 0;
  const core = RoomCore.create(store, { now: () => clock, seed: () => `measure-${clock}` }, { code: 'MEASUR', gameId: 'apex', name: 'P0', th: 't0' });
  for (let i = 1; i < 6; i++) core.join(`P${i}`, `t${i}`);
  const all = new Set([0, 1, 2, 3, 4, 5]);
  const send = (seat: number, m: Record<string, unknown>) => core.handle(seat, { id: `m${++ids}`, v: core.version, ...m } as never, all);
  send(0, { t: 'config', config: { mode: 'championship', season: 5, cars: 8 } });
  send(0, { t: 'start' });
  core.presence(all);
  let peakState = 0, steps = 0;
  const raceStates: number[] = [];
  while (core.status === 'playing' && steps++ < 20_000) {
    clock += 1000;
    const actors = core.view(0, all).actors;
    for (const seat of actors) {
      const b = apex.bot!(core.view(seat, all).game as AView);
      if (b) for (const a of b.actions) send(seat, { t: 'act', a });
    }
    const st = store.state as AState;
    const size = JSON.stringify(st).length;
    peakState = Math.max(peakState, size);
    if (st.race) raceStates.push(size);
  }
  expect(core.status).toBe('over');
  const st = store.state as AState;
  const replayBytes = st.replays.map((r) => exportReplay(r).length);
  const history = JSON.stringify(store.history).length;
  const kb = (b: number) => `${f1(b / 1024)} KB`;
  out.push(
    '', '## Storage (a 5-race championship, 6 people and 2 computer cars, Durable Object rows)', '',
    '| Measure | Size |', '|---|---|',
    `| Room state, peak | ${kb(peakState)} |`,
    `| Room state at the end | ${kb(JSON.stringify(st).length)} |`,
    `| One race replay, mean (export file) | ${kb(avg(replayBytes))} |`,
    `| History rows, whole season (${store.history.length} rows) | ${kb(history)} |`,
    `| Idempotency rows kept | ${store.actions.size} |`,
    `| Server steps to finish the season | ${steps} |`,
    '',
    'The state is one SQLite row rewritten per accepted action, well under the 2 MB row limit and the free tier’s',
    '5 GB per account. History rows hold only public text. Retention deletes the row, its history and its alarm.',
  );

  const report = out.join('\n') + '\n';
  writeFileSync('docs/APEX_BALANCE.md', report);
  console.log(report);
  // A sanity floor, not a tuning target: no slot may dominate a circuit.
  expect(Math.max(...poleShare)).toBeLessThan(0.6);
});
