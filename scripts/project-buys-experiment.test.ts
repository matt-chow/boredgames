/**
 * Project Buys comparison (CC-STAGE-5): not part of the game. Plays paired seeded tables on the live rules, where every
 * Crown Project stage uses a Buy, against a counterfactual where a contribution needs a Buy in hand but gives it back.
 * Writes docs/PROJECT_BUYS_RESULTS.md. EXPERIMENT_GAMES sets games per mode and player count (default 40).
 * One process, one game at a time, so it fits a low-memory machine.
 */
import { writeFileSync } from 'node:fs';
import { it } from 'vitest';
import type { DeckAction, DeckState, DeckView } from '../src/engine/deckbuilder';
import { clockwork as game } from '../src/games/clockwork';
import { botMove, PROFILES } from '../src/games/clockwork/rules/bot';

const N = Number(process.env.EXPERIMENT_GAMES ?? 40);
const COUNTS = [2, 3, 4, 5, 6];
const STEP_CAP = 30_000;
const MODES = [
  { id: 'buys', name: 'Live: each stage uses a Buy' },
  { id: 'free', name: 'Counterfactual: a stage needs a Buy but keeps it' },
] as const;

interface Row {
  rounds: number;
  ended: string;
  seats: string[];
  winners: number[];
  completed: number;
  stages: number;
  topShare: number | null;
  zero: number;
  marketBought: number;
}

function play(free: boolean, players: number, seed: string, i: number): Row {
  const profiles = Array.from({ length: players }, (_, k) => PROFILES[1 + ((i * 7 + k * 5) % (PROFILES.length - 1))]);
  let s = game.setup({ playerCount: players, seed, config: { market: [], bans: [], projects: [], sets: ['core', 'crown'] } }) as DeckState;
  let marketBought = 0;
  let stuck = false;
  for (let step = 0; step < STEP_CAP && !s.over; step++) {
    const [seat] = game.actors(s);
    const move = botMove(game.project(s, seat) as DeckView, profiles[seat], 0);
    let done = false;
    for (const a of (move?.actions ?? []) as DeckAction[]) {
      const r = game.apply(s, seat, a);
      if (!r.ok) continue;
      if (a.type === 'buy' && s.market.includes(a.pile)) marketBought++;
      if (free && a.type === 'claim' && !r.state.over && r.state.turn.seat === seat) r.state.turn.buys++;
      s = r.state;
      done = true;
      break;
    }
    if (!done) {
      stuck = true;
      break;
    }
  }
  const finals = s.over ? (game.project(s, 0) as DeckView).final! : [];
  const results = s.over ? game.results!(s)! : [];
  const project = finals.map((f) => f.breakdown.projects);
  const sum = project.reduce((a, b) => a + b, 0);
  const done = s.projects.filter((p) => p.by !== null).length;
  return {
    rounds: (s.turn.number + 1) / players,
    ended: stuck ? 'stuck' : !s.over ? 'cap' : (s.supply.monument?.length ?? 1) === 0 ? 'grand-duchy' : done >= 5 ? 'projects' : 'piles',
    seats: profiles.map((p) => p.name),
    winners: results.filter((r) => r.winner).map((r) => r.seat),
    completed: done,
    stages: s.projects.flatMap((p) => p.stages ?? [p]).filter((x) => x.by !== null).length,
    topShare: sum ? Math.max(...project) / sum : null,
    zero: project.filter((x) => x === 0).length,
    marketBought,
  };
}

const mean = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const f1 = (x: number) => x.toFixed(1);
const pct = (x: number) => `${Math.round(x * 100)}%`;

it('compares Buy-consuming Project contributions with free ones', () => {
  const lines = [
    '# Project Buys comparison',
    '',
    `Generated by \`npx vitest run --config scripts/project-buys.config.ts\`. ${N} paired games per mode and player count, default sets, live bots, live edition 4 rules.`,
    'The counterfactual still needs a Buy in hand to fund a stage but gives it back, so a contribution never costs a card purchase.',
    '',
    '| Players | Mode | Rounds | All 5 complete | Stages funded | Ended by Projects / Grand Duchy / piles | Top Project-Renown share | Players with 0 Project Renown | Market cards bought |',
    '|---|---|---|---|---|---|---|---|---|',
  ];
  const wins: Record<string, Record<string, { n: number; w: number }>> = {};
  for (const n of COUNTS) {
    for (const mode of MODES) {
      const rows = Array.from({ length: N }, (_, i) => play(mode.id === 'free', n, `buys-${n}-${i}`, i));
      const fin = rows.filter((r) => r.ended !== 'cap' && r.ended !== 'stuck');
      const share = (e: string) => pct(fin.filter((r) => r.ended === e).length / Math.max(1, fin.length));
      lines.push(
        `| ${n} | ${mode.id} | ${f1(mean(fin.map((r) => r.rounds)))} | ${pct(fin.filter((r) => r.completed >= 5).length / Math.max(1, fin.length))} | ${f1(mean(fin.map((r) => r.stages)))} / 11 | ${share('projects')} / ${share('grand-duchy')} / ${share('piles')} | ${pct(mean(fin.flatMap((r) => (r.topShare === null ? [] : [r.topShare]))))} | ${f1(mean(fin.map((r) => r.zero)))} | ${f1(mean(fin.map((r) => r.marketBought)))} |`,
      );
      if (fin.length < rows.length) lines.push(`|  | ${mode.id} | ${rows.length - fin.length} games hit the cap or stuck |  |  |  |  |  |  |`);
      for (const r of fin)
        r.seats.forEach((name, k) => {
          const e = ((wins[mode.id] ??= {})[name] ??= { n: 0, w: 0 });
          e.n++;
          if (r.winners.includes(k)) e.w += 1 / r.winners.length;
        });
    }
  }
  lines.push('', '## Bot strategy win rates, all player counts', '', '| Strategy | Live | Counterfactual |', '|---|---|---|');
  for (const name of Object.keys(wins.buys).sort()) {
    const rate = (m: string) => (wins[m]?.[name] ? `${pct(wins[m][name].w / wins[m][name].n)} of ${wins[m][name].n}` : '–');
    lines.push(`| ${name} | ${rate('buys')} | ${rate('free')} |`);
  }
  writeFileSync('docs/PROJECT_BUYS_RESULTS.md', lines.join('\n') + '\n');
});
